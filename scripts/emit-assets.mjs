// Minify the SPA stylesheet and client script into src/generated/client-assets.ts.
// Run after editing src/ui.ts: node scripts/emit-assets.mjs
// The worker serves the minified bytes and checks the stored hash against the
// source so a forgotten run fails tests instead of shipping a stale bundle.
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const esbuild = require('esbuild');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outfile = '/tmp/jamwerk-dump-shell.mjs';

await esbuild.build({
  entryPoints: [join(root, 'scripts/dump-shell.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  outfile,
});

const dumped = spawnSync(process.execPath, [outfile], { encoding: 'utf8' });
if (dumped.status !== 0) {
  console.error(dumped.stderr || dumped.stdout);
  process.exit(dumped.status || 1);
}
const raw = JSON.parse(readFileSync('/tmp/jamwerk-shell.json', 'utf8'));
const css = await esbuild.transform(raw.css, { loader: 'css', minify: true });
const js = await esbuild.transform(raw.js, { loader: 'js', minify: true, target: 'es2020' });
if (css.warnings.length || js.warnings.length) {
  console.warn(css.warnings, js.warnings);
}
try {
  // The client is a classic script, not a module.
  new Function(js.code);
} catch (err) {
  console.error('Minified client script is not valid JS:', err);
  process.exit(1);
}

mkdirSync(join(root, 'src/generated'), { recursive: true });
const out = `// Generated by scripts/emit-assets.mjs — do not edit.
export const RAW_CSS_HASH = ${JSON.stringify(raw.cssHash)};
export const RAW_JS_HASH = ${JSON.stringify(raw.jsHash)};
export const APP_CSS = ${JSON.stringify(css.code)};
export const APP_JS = ${JSON.stringify(js.code)};
`;
writeFileSync(join(root, 'src/generated/client-assets.ts'), out);
console.log(`assets: css ${raw.css.length} -> ${css.code.length}, js ${raw.js.length} -> ${js.code.length}`);
